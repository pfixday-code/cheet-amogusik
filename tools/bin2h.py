#!/usr/bin/env python3
"""Embeds classes.dex as a C++ byte array: bin2h.py <classes.dex> <menu_dex.h>"""
import sys
from pathlib import Path


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: bin2h.py <classes.dex> <output.h>", file=sys.stderr)
        return 2
    data = Path(sys.argv[1]).read_bytes()
    if len(data) < 0x70 or data[:4] != b"dex\n":
        print(f"{sys.argv[1]} is not a dex file", file=sys.stderr)
        return 1
    rows = ["    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + "," for i in range(0, len(data), 16)]
    text = "\n".join([
        "// Generated by tools/bin2h.py from classes.dex. Do not edit.",
        "#pragma once",
        "#include <cstddef>",
        "",
        "alignas(16) inline constexpr unsigned char kMenuDex[] = {",
        *rows,
        "};",
        "inline constexpr size_t kMenuDexSize = sizeof(kMenuDex);",
        "",
    ])
    Path(sys.argv[2]).write_text(text, encoding="ascii")
    print(f"wrote {sys.argv[2]} ({len(data)} bytes of dex)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
